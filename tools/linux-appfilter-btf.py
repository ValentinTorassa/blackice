#!/usr/bin/env python3
"""Read local kernel BTF and emit reviewed constants. Never loads or attaches BPF.

The runtime accepts only the embedded release AND full BTF hash. Regenerating this
file changes a privileged build input and therefore needs a new security review.
"""
from pathlib import Path
import hashlib
import os
import struct


class BTF:
    def __init__(self, data):
        if len(data) < 24:
            raise ValueError('short BTF header')
        magic, version, flags, size, toff, tlen, soff, slen = struct.unpack_from('<HBBIIIII', data)
        if (magic, version, flags) != (0xeb9f, 1, 0) or size < 24:
            raise ValueError('unsupported BTF header')
        if size + max(toff + tlen, soff + slen) > len(data):
            raise ValueError('BTF section outside file')
        if not (toff + tlen <= soff or soff + slen <= toff):
            raise ValueError('overlapping BTF sections')
        self.strings = data[size + soff:size + soff + slen]
        if self.strings[:1] != b'\0':
            raise ValueError('invalid BTF string table')
        self.types = [None]
        pos, end = size + toff, size + toff + tlen
        while pos < end:
            if pos + 12 > end:
                raise ValueError('short BTF type')
            name, info, value = struct.unpack_from('<III', data, pos)
            kind, count = (info >> 24) & 31, info & 65535
            sizes = {1: 4, 2: 0, 3: 12, 4: count * 12, 5: count * 12,
                     6: count * 8, 7: 0, 8: 0, 9: 0, 10: 0, 11: 0,
                     12: 0, 13: count * 8, 14: 4, 15: count * 12,
                     16: 0, 17: 4, 18: 0, 19: count * 12}
            if kind not in sizes or pos + 12 + sizes[kind] > end:
                raise ValueError('invalid BTF kind or extent')
            body = data[pos + 12:pos + 12 + sizes[kind]]
            self.types.append(dict(name=self.string(name), kind=kind, value=value,
                                   count=count, flag=bool(info >> 31), body=body))
            pos += 12 + sizes[kind]

    def string(self, offset):
        if offset >= len(self.strings):
            raise ValueError('BTF string outside section')
        end = self.strings.find(b'\0', offset)
        if end < 0:
            raise ValueError('unterminated BTF string')
        return self.strings[offset:end].decode('utf-8')

    def named(self, name, kind):
        matches = [i for i, t in enumerate(self.types) if t and t['name'] == name and t['kind'] == kind]
        if len(matches) != 1:
            raise ValueError(f'expected exactly one {name} (kind {kind}), got {matches}')
        return matches[0]

    def field(self, type_name, member):
        def walk(tid, base, depth):
            if depth > 16 or tid <= 0 or tid >= len(self.types):
                raise ValueError('invalid nested BTF member')
            t = self.types[tid]
            if t['kind'] not in (4, 5):
                return []
            found = []
            for i in range(t['count']):
                name, child, bits = struct.unpack_from('<III', t['body'], i * 12)
                name = self.string(name)
                if name not in ('', member):
                    continue
                if (t['flag'] and bits >> 24) or bits % 8:
                    raise ValueError('bitfields are not supported')
                offset = base + bits // 8
                if name == member:
                    found.append(offset)
                else:
                    found.extend(walk(child, offset, depth + 1))
            return found
        matches = [i for i, t in enumerate(self.types) if t and t['name'] == type_name and t['kind'] in (4, 8)]
        if len(matches) != 1:
            raise ValueError('ambiguous field type')
        tid = matches[0]
        if self.types[tid]['kind'] == 8:
            tid = self.types[tid]['value']
        found = walk(tid, 0, 0)
        if len(found) != 1 or found[0] > 32767:
            raise ValueError(f'invalid/ambiguous member {type_name}.{member}: {found}')
        return found[0]


def main():
    path = Path('/sys/kernel/btf/vmlinux')
    data = path.read_bytes()
    btf = BTF(data)
    release = os.uname().release
    if release != '6.12.113+deb13-amd64' or os.uname().machine != 'x86_64':
        raise ValueError('this initial pin supports only the reviewed Debian x86_64 kernel')
    fields = {
        'task_struct': ['tgid', 'pid', 'group_leader', 'mm', 'signal', 'real_cred'],
        'mm_struct': ['exe_file'], 'file': ['f_inode'], 'inode': ['i_ino', 'i_sb', 'i_generation'],
        'super_block': ['s_dev'], 'linux_binprm': ['file'], 'signal_struct': ['live'],
        'atomic_t': ['counter'], 'cred': ['uid'], 'kuid_t': ['val'], 'bpf_iter__task': ['task'],
    }
    result = ['//! Generated by tools/linux-appfilter-btf.py; review changes before installing.',
              f'pub const release = "{release}";',
              f'pub const btf_sha256 = "{hashlib.sha256(data).hexdigest()}";']
    for type_name, members in fields.items():
        for member in members:
            offset = btf.field(type_name, member)
            result.append(f'pub const {type_name}_{member}: i16 = {offset};')
    for event in ['sched_process_exec', 'sched_process_fork', 'sched_process_exit']:
        result.append(f'pub const {event}_btf_id: u32 = {btf.named("btf_trace_" + event, 8)};')
    result.append(f'pub const iter_task_btf_id: u32 = {btf.named("bpf_iter_task", 12)};')
    output = Path(__file__).resolve().parents[1] / 'src/linux/apps/kernel_pin.zig'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(result) + '\n')
    print(output)
    print('kernel BTF SHA-256:', hashlib.sha256(data).hexdigest())


if __name__ == '__main__':
    main()
